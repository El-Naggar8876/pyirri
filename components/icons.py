def get_icon(
    icon: Icon,
    size: int = 24,
    color: str = "currentColor",
    stroke_width: float = 2,
    css_class: str = ""
) -> str:
    """
    Get SVG icon HTML.
    
    Args:
        icon: Icon enum value
        size: Icon size in pixels
        color: Icon color (CSS color value)
        stroke_width: Stroke width for icon lines
        css_class: Additional CSS class to apply
    
    Returns:
        SVG HTML string
    """
    icon_name = icon.value if isinstance(icon, Icon) else icon
    svg_content = ICON_SVGS.get(icon_name, ICON_SVGS["info"])
    
    return f'''<svg 
        xmlns="http://www.w3.org/2000/svg" 
        width="{size}" 
        height="{size}" 
        viewBox="0 0 24 24" 
        fill="none" 
        stroke="{color}" 
        stroke-width="{stroke_width}" 
        stroke-linecap="round" 
        stroke-linejoin="round"
        class="icon {css_class}"
    >{svg_content}</svg>'''


def icon_button(icon: Icon, label: str = "", size: int = 20, **kwargs) -> str:
    """
    Generate HTML for an icon button.
    
    Args:
        icon: Icon enum value
        label: Optional text label
        size: Icon size
        **kwargs: Additional attributes
    
    Returns:
        HTML string for icon button
    """
    icon_svg = get_icon(icon, size=size)
    label_html = f'<span style="margin-left: 0.5rem;">{label}</span>' if label else ""
    
    return f'''<button class="icon-button" style="display: inline-flex; align-items: center; gap: 0.25rem;">
        {icon_svg}{label_html}
    </button>'''
